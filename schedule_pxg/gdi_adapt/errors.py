"""Исключения проекта. Все наследуются от AdaptError: runner ловит их по одной скважине и идёт дальше."""


class AdaptError(Exception):
    """Базовая ошибка адаптации одной скважины."""


class WellNotWorkingError(AdaptError):
    """Скважина не работала ни на дату ГДИ, ни на каком-либо шаге модели."""


class ModelDataError(AdaptError):
    """Не удалось прочитать данные скважины из модели (нет скважины, нет открытых перфораций...)."""


class GdiDataError(AdaptError):
    """Проблема во входных данных ГДИ (нет колонок, нет подходящих режимов...)."""
