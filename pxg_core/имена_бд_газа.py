"""Канонические имена столбцов «БД по учету газа» — общий словарь для всех приложений.

В листе «БД» один параметр — один столбец. Исходные названия из шапки Excel длинные и разные от файла к файлу
(«Отобрано газа из ПХГ за сутки / Всего по ПЗРГ - за сутки по ПХГ» и т.п.), поэтому главные величины пишутся под
стабильными именами из этого файла. Приложения (Атлас, Карты ГСП, Скедул, нормировка ПЗРГ) читают БД по этим именам.
Старые выгрузки с исходными названиями читаются по подстроке, как раньше (`найти_столбец`).

Главные колонки идут в листе первыми, в порядке MAIN_COLUMNS. Атлас (gas_atlas) держит те же строки у себя: менять имя
здесь — значит менять и там (тест слепка проверяет совпадение имён).
"""
import re

WITHDRAW = "Отбор из ПХГ, тыс. м³/сут"          # отбор по объекту за сутки (= «Всего по ПЗРГ - за сутки по ПХГ»)
INJECT = "Закачка в ПХГ, тыс. м³/сут"           # закачка по объекту за сутки (= «Закачано в ПХГ за СУТКИ»)
WATER = "Добыча пластовой воды, м³/сут"         # вынос пластовой жидкости по объекту (= «Пластовая жидкость … Всего по ПХГ»)
WELLS_TOTAL = "Работающие скважины, всего по ПХГ"
WELLS_GSP = "Работающие скважины, ГСП-%d"     # ГСП-1 … ГСП-9: среднее число работающих скважин в сутки

MAIN_COLUMNS = [WITHDRAW, INJECT, WATER, WELLS_TOTAL] + [WELLS_GSP % n for n in range(1, 10)]

_WELLS = re.compile(r"(работающих скважин|количество скважин).*/\s*(всего по пхг|гсп\s*-?\s*(\d+))$")


def param_key(label) -> str:
    """Ключ параметра для сравнения: регистр, пробелы, «-» и «_» не различаются."""
    text = re.sub(r"\s+", " ", str(label)).strip().lower()
    return re.sub(r"\s*([-_])\s*", r"\1", text)


def canonical_name(label):
    """Каноническое имя для исходного названия столбца; None, если такого параметра в словаре нет.

    Рабочие скважины — и отбор («Среднее количество работающих скважин … / ГСП-1»), и закачка («Среднесуточное
    количество скважин / ГСП-1») — пишутся в один и тот же столбец: строка БД задаёт режим.
    """
    key = param_key(label)
    if "всего по пзрг-за сутки по пхг" in key:
        return WITHDRAW
    if key.startswith("закачано в пхг за сутки"):
        return INJECT
    if "пластовая жидкость (м3) / всего по пхг" in key:
        return WATER
    m = _WELLS.search(key)
    if m:
        return WELLS_TOTAL if m.group(2) == "всего по пхг" else WELLS_GSP % int(m.group(3))
    return None


def найти_столбец(columns, canonical: str, legacy_part: str) -> str:
    """Столбец БД по каноническому имени; для старых выгрузок — по подстроке исходного названия (ровно один столбец).

    Бросает ValueError, если ни каноническое имя, ни подстрока не нашли столбец или подстрока подошла несколько раз.
    """
    columns = list(columns)
    if canonical in columns:
        return canonical
    hits = [c for c in columns if legacy_part in str(c)]
    if len(hits) != 1:
        raise ValueError("В «БД по учету газа» нет столбца «%s» (искали по подстроке «%s»: найдено %d)"
                         % (canonical, legacy_part, len(hits)))
    return hits[0]
