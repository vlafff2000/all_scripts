def test_w410_short_reach_takes_field_depths_below_device_stop():
    """Скв. 410: прибор остановился на 763,4, ИЗ 782,0 (недоход 18,6 м) — фильтр по ГИС 758,2–763,2 обрезан остановкой прибора:
    элементы ниже остановки берутся по промысловым данным (подсказка с причиной); выше остановки — по ГИС; ИЗ не меняется."""
    frames = _w410()
    g = frames["gis"].set_index("Элемент")
    f = g.loc["Фильтр"]
    # комбинированный подход: верх фильтра отбит ГИС (758,2, выше остановки прибора), низ ГИС обрезан остановкой (763,2) — низ по промысловым (772,45)
    assert (f["Верх интервала, м"], f["Низ интервала, м"]) == (758.2, 772.45)
    assert f["Источник глубины"].startswith("ГИС (верх) + промысловые данные (низ): прибор остановился на 763,4 м, ИЗ 782 м")
    assert g.loc["НКТ", "Низ интервала, м"] == 739.0 and g.loc["НКТ", "Источник глубины"] == "ГИС"        # выше остановки — по ГИС
    assert g.loc["Искусственный забой", "Верх интервала, м"] == 782.0
    assert (g.loc["Клапанная система", "Верх интервала, м"], g.loc["Клапанная система", "Низ интервала, м"]) == (772.45, 773.0)     # ниже остановки не сдвигается
    assert any("недоход прибора ГИС" in m for m in frames["Проверка"]["Сообщение"])
    # элементы целиком ниже остановки (ГИС «не охвачен») — по промысловым данным
    assert (g.loc["Клапанная система", "Верх интервала, м"], g.loc["Клапанная система", "Низ интервала, м"]) == (772.45, 773.0)
    # ручное переопределение и выключение проверки: фильтр по ГИС
    keep = _w410(keep_gis=["410"])["gis"].set_index("Элемент")
    assert keep.loc["Фильтр", "Низ интервала, м"] == 763.2 and keep.loc["Фильтр", "Источник глубины"] == "ГИС"
    off = _w410(short_thr=0)["gis"]
    assert not any("недоход" in str(x) for x in off["Источник глубины"])


