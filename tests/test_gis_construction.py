def _t(rows):
    """Таблица Word из строк: текст ячейки; None — продолжение вертикального объединения (как w:vMerge continue)."""
    out = []
    for r in rows:
        cells, x = [], 0.0
        for c in r:
            cells.append(wt.Cell("" if c is None else c, x, x + 1, c is None))
            x += 1
        out.append(wt.TRow(cells))
    return wt.Table(out, 3)


