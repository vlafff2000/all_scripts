def test_kinds():
    assert extract.doc_kind(KRS) == "krs" and extract.doc_kind(GIS) == "gis" and extract.doc_kind(GDI) == "gdi"


def test_dates():
    assert extract.ru_date("от « 31 » 07 2026 года") == "31.07.2026"
    assert extract.ru_date("от «07» сентября 2026 года") == "07.09.2026"
    assert extract.ru_date("27.04.2026г") == "27.04.2026"


def test_krs():
    s = extract.extract_krs(KRS, "scan.pdf")
    cols, rows = s["КРС_акты"]
    assert len(rows) == 2
    kap, acid = rows
    assert kap[1] == "533" and kap[2] == "438834" and kap[3] == "Касимовского" and kap[5] == "31.07.2026" and "рукописный" in kap[-1]
    assert "Яковенко В.Ю." in kap[12] and kap[11] == "799.91"
    assert acid[4] == "Кислотная обработка ПЗП" and acid[6] == "31.08.2026" and acid[7] == "07.09.2026"
    inj = s["КРС_закачки"][1]
    assert [r[3] for r in inj] == [0.46, 0.46] and inj[0][2] == "01.09.2026" and inj[0][5] == "В"


def test_gis():
    s = extract.extract_gis(GIS, "g.pdf")
    c, rows = s["ГИС_заключения"]
    r = dict(zip(c, rows[0]))
    assert r["Скважина"] == "64" and r["Дата ГИС"] == "29.04.2026" and r["Забой по доходу прибора, м"] == "436.3"
    assert r["ГВК, м"] == "423.5" and r["ГВК абс. отм., м"] == "-311.3" and r["Кг, %"] == "30" and r["Нг, м"] == "0.7"
    assert s["Забой_доход_прибора"][1][0][3] == "436.3"
    assert s["ГВК_по_датам"][1][0][2:6] == ["15.05.2025", "нейтральный", "423.5", "-311.3"]
    kg = s["ГИС_Кг_по_интервалам"][1]
    assert len(kg) == 4 and kg[0][2] == "05.2025" and kg[0][7] == "30" and kg[3][7] == "<20" and kg[3][2] == "04.2026"
    assert s["ГИС_комплекс"][1][0][3] == "2НГК ГК"


def test_gdi():
    s = extract.extract_gdi(GDI, "r.pdf")
    c, rows = s["ГДИ_исследования"]
    assert rows[0][2] == "533" and rows[0][3] == "07.09.2026" and rows[0][4] == "ИД" and rows[0][5] == 148.0
    assert s["ГДИ_перфорация"][1][0][3:] == [779.0, 795.0]
    modes = s["ГДИ_режимы"][1]
    assert [m[2] for m in modes] == ["Статика", "Режим 1", "Режим 2"]
    assert modes[1][3] == 20.0 and modes[1][5] == 534.78 and modes[1][8] == 1.97661
    res = dict(zip(*[s["ГДИ_результаты"][0], s["ГДИ_результаты"][1][0]]))
    assert res["Рпл на ИП, кгс/см2"] == 104.725 and res["b"] == 5.5452e-04 and res["Своб. дебит, тыс.м3/сут"] == 3447.2


def test_xlsx(tmp_path):
    kind, sheets = extract.extract(GDI, "r.pdf")
    p = extract.write_xlsx(sheets, str(tmp_path / "db.xlsx"))
    assert kind == "gdi" and "ГДИ_режимы" in load_workbook(p).sheetnames
