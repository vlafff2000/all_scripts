"""Отчёт ГИС без линий в таблицах (форма НПФ «Оренбурггазгеофизика», Гатчинское ПХГ): строки текста — как их отдаёт и текстовый слой PDF, и абзацы вывода OCR."""
from pxg_core import gis_report as gr, word_tables as wt

LINES = """Заключение по результатам интерпретации данных
геофизических исследований в скважине
ПХГ Гатчинское ПХГ
СКВАЖИНА №118
АЛЬТИТУДА ЗЕМЛИ 109.31 м
ДАТА ИССЛЕДОВАНИЙ 27.04.2026г
Сведения по скважине (промысловые данные):
Текущий забой 419.59 419.6 (доход приборов)
РЕЗУЛЬТАТЫ ИССЛЕДОВАНИИ
1. Отбивка текущего забоя
Максимальный доход прибора с учетом «мёртвой» зоны составляет - 419.6 м.
2. Определение термобарических условий и фазового заполнения ствола скважины
Таблица распределение давления и температуры по стволу скважины:
Глубина, м Температура, °С Давление, кгс/см2
300.0 17.3 24.8
414.6 кровля пласта-коллектора 18.9 30.0
419.5 доход 19.3 30.5
Таблица фазового заполнения ствола скважины:""".split("\n")


def _rep():
    return gr.parse_blocks([wt.Para(x) for x in LINES], "118.pdf")


def test_well_number_is_taken_from_number_sign():
    r = _rep()
    assert r.well == "118" and r.alt == 109.31


def test_template_reach_from_sentence_with_dead_zone():
    kinds = {(b["Вид"], b["Глубина, м"]) for b in _rep().bottoms}
    assert (gr.KIND_TEMPLATE, 419.6) in kinds


def test_current_bottom_row_in_plain_text():
    kinds = {(b["Вид"], b["Глубина, м"]) for b in _rep().bottoms}
    assert (gr.KIND_FIELD, 419.59) in kinds


def test_thermo_rows_from_plain_text():
    th = {(t["Глубина, м"], t["Температура, °C"], t["Давление, кгс/см²"]) for t in _rep().thermo}
    assert th == {(300.0, 17.3, 24.8), (414.6, 18.9, 30.0), (419.5, 19.3, 30.5)}
    top = next(t for t in _rep().thermo if t["Глубина, м"] == 414.6)
    assert top["Пометка (как в отчёте)"].startswith("кровля")


def test_heading_and_first_row_in_one_paragraph():
    """В PDF заголовок таблицы и её первая строка приходят одним абзацем."""
    blocks = [wt.Para("СКВАЖИНА №118"), wt.Para("Глубина, м Температура, °С Давление, кгс/см2\n300.0 17.3 24.8"), wt.Para("414.6 кровля пласта-коллектора 18.9 30.0")]
    r = gr.parse_blocks(blocks, "x.pdf")
    assert [t["Глубина, м"] for t in r.thermo] == [300.0, 414.6]
