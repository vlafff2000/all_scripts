def test_w58_tech_state_all_findings_once():
    """Скв. 58: всё, что сказано о техсостоянии, — по одной записи (повтор в «Выводах» склеен), заголовки и задачи отчёта — не записи."""
    rows = ts.read(_rep(), [wt.Para(t) for t in W58])
    got = {(r["Вид"], r["Есть"], r["Интервалы"]) for r in rows}
    assert got == {("Толщина стенки", "да", "0–768.4"), ("Толщина стенки", "да", "0–752.7"), ("Дефекты НКТ/ЭК", "нет", ""),
                   ("Насыщение пласта-коллектора", "да", "765.5–780.2"), ("Скопление газа: за колонной", "да", "5.1–7.7"),
                   ("Изменение НГК из-за конструкции", "да", "752.7–770.4"), ("Скопление газа: по стволу", "нет", ""), ("Заколонный переток", "нет", "")}
    assert len(rows) == 8
    by = {(r["Вид"], r["Интервалы"]): r for r in rows}
    ek = by[("Толщина стенки", "0–768.4")]
    assert (ek["Колонна"], ek["Толщина мин, мм"], ek["Толщина макс, мм"]) == ("ЭК", 7.0, 8.6) and by[("Толщина стенки", "0–752.7")]["Колонна"] == "НКТ"
    assert by[("Насыщение пласта-коллектора", "765.5–780.2")]["Насыщение"] == "газонасыщен (уплотненный осадок)"
    assert by[("Скопление газа: за колонной", "5.1–7.7")]["Метод"] == "НГК"
    assert by[("Дефекты НКТ/ЭК", "")]["Колонна"] == "НКТ и ЭК"


def test_clay_cap_list_typo_and_negatives():
    paras = ["Скопления газа отмечаются в проницаемых прослоях глинистой покрышки щигровского горизонта (D3sc):",
             "в проницаемом прослое в интервале 788,9 – 790,0 м, Нг=1,1 м, Кг=45 %;",
             "Скоплений газа отмечаются в проницаемых прослоях глинистой покрышки в интервалах 754.0 – 756.5 м, 757.7 – 759.0 м.",
             "Скоплений газа в проницаемых прослоях глинистой покрышки и вышележащих отложениях не выявлено.",
             "Скопления газа за колонной и вышележащих горизонтах в интервале исследований не выявлено.",
             "Скопления газа отмечаются в каверне под башмаком эксплуатационной колонны (760,6-761,7м).",
             "Перфорация ЭК отмечается в интервале 769,1 – 788,1 м, в остальном интервале исследований толщина стенок эксплуатационной колонны изменяется от 7,2 до 8,4 мм."]
    rows = ts.read(_rep(), [wt.Para(t) for t in paras])
    got = [(r["Вид"], r["Есть"], r["Интервалы"]) for r in rows]
    assert ("Скопление газа: глинистая покрышка", "да", "788.9–790") in got          # подпись списка + строка списка
    assert ("Скопление газа: глинистая покрышка", "да", "754–756.5; 757.7–759") in got     # «Скоплений … отмечаются» с интервалами — есть
    assert ("Скопление газа: глинистая покрышка", "нет", "") in got
    assert ("Скопление газа: за колонной", "нет", "") in got
    assert ("Скопление газа: под башмаком колонны", "да", "760.6–761.7") in got
    assert any(k == "Толщина стенки" and r["Толщина мин, мм"] == 7.2 for (k, _h, _i), r in zip(got, rows))
    assert not any(r["Текст"].endswith(":") for r in rows)                             # подпись списка сама записью не стала
    cap = next(r for r in rows if r["Интервалы"] == "788.9–790")
    assert (cap["Нг, м"], cap["Кг (как в отчёте)"]) == (1.1, "Кг=45 %")


